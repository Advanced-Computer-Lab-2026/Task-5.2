import express from 'express';
import morgan from 'morgan';
import cors from 'cors';
import helmet from 'helmet';
import authRoutes from './routes/auth.js';
import listingRoutes from './routes/listings.js';
import userRoutes from './routes/users.js';
import reviewRoutes from './routes/reviews.js';

const app = express();

// Security headers. The Content-Security-Policy is the browser-enforced second
// layer behind DOMPurify: even if some markup slipped through sanitization,
// the browser refuses inline <script>, inline event handlers (onerror=...) and
// javascript: URLs, and only loads scripts from our own origin.
app.use(
  helmet({
    contentSecurityPolicy: {
      useDefaults: false,
      directives: {
        defaultSrc: ["'self'"],
        scriptSrc: ["'self'"],          // no 'unsafe-inline', no 'unsafe-eval'
        scriptSrcAttr: ["'none'"],      // block inline event-handler attributes
        styleSrc: ["'self'"],
        imgSrc: ["'self'", 'data:'],
        connectSrc: ["'self'"],
        fontSrc: ["'self'"],
        objectSrc: ["'none'"],          // no <object>/<embed> plugins
        baseUri: ["'self'"],            // stop <base href> hijacking relative URLs
        formAction: ["'self'"],
        frameAncestors: ["'none'"]      // no clickjacking via framing
      }
    }
  })
);
app.use(morgan('dev'));
app.use(cors({ origin: 'http://localhost:5175', credentials: false }));
app.use(express.json());

app.get('/api/health', (req, res) => res.json({ ok: true }));

app.use('/api/auth', authRoutes);
app.use('/api/listings', listingRoutes);
app.use('/api/users', userRoutes);
app.use('/api/reviews', reviewRoutes);

// Not found
app.use((req, res) => {
  res.status(404).json({ message: 'Not Found' });
});

// Error handler
app.use((err, req, res, next) => {
  console.error(err);
  res.status(err.status || 500).json({ message: err.message || 'Server Error' });
});

export default app;
